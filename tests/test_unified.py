    def test_42_api_returns_source_to_output_transforms(self):
        report,_=self.process(self.recipe())
        for group in report['containers']:
            for region in group['regions']:
                H=np.asarray(region['input_to_final_homography'])
                self.assertEqual(H.shape,(3,3));self.assertTrue(np.isfinite(H).all())
                x0,y0,_,_=region['view_box_xyxy_exclusive']
                q=np.asarray(region['quad_tl_tr_br_bl_in_view'])+np.array([x0,y0])
                out=cv2.perspectiveTransform(q[None].astype(np.float64),H)[0]
                self.assertGreaterEqual(float(out.min()),-1e-4)
                self.assertLessEqual(float(out[:,0].max()),report['output_size_wh'][0])

