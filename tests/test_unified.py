# The original sample photographs (sources/, examples/) are not distributed with
# this repository; tests that exercise the packaged recipes skip gracefully.
# Probe a file only the private bundle has: the seeded demo samples also live
# in sources/ during public test runs, so directory existence is not enough.
PRIVATE_BUNDLE = (ROOT / 'sources' / 'single_grey.png').is_file()


class UnifiedTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.shared = tempfile.TemporaryDirectory()
        cls.fixtures = Path(cls.shared.name)
        # Two independent textured planes with known overlap; not generated by a learned model.
        for seed in (5, 17):
            rng = np.random.default_rng(seed)
            im = rng.integers(40, 215, (220, 700, 3), dtype=np.uint8)
            im = cv2.GaussianBlur(im, (3, 3), .65)
            for i in range(50):
                x,y = int(rng.integers(10,690)),int(rng.integers(10,210))
                value = int(rng.integers(20,235))
                cv2.circle(im,(x,y),int(rng.integers(3,10)),(value,)*3,-1)
            cs.save_image(cls.fixtures / f"plane_{seed}.png", im)
            cs.save_image(cls.fixtures / f"left_{seed}.png", im[:,:450])
            cs.save_image(cls.fixtures / f"right_{seed}.png", im[:,250:])
        cs.save_image(cls.fixtures / 'blank.png', np.full((220,450,3),127,np.uint8))

    @classmethod
    def tearDownClass(cls):
        cls.shared.cleanup()

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.base = Path(self.temp.name)
        self.counter = 0

    def tearDown(self):
        self.temp.cleanup()

    def recipe(self, name='single_grey'):
        if not PRIVATE_BUNDLE:
            raise unittest.SkipTest(
                'private sample bundle (sources/, examples/) is not part of this repository')
        config = json.loads((ROOT/'configs'/f'{name}.json').read_text())
        for source in config['sources'].values():
            source['path'] = str((ROOT/'configs'/source['path']).resolve())
        return config

    def process(self, cfg, **kwargs):
        self.counter += 1
        cpath = self.base/f'config_{self.counter}.json'
        cpath.write_text(json.dumps(cfg))
        out = self.base/f'run_{self.counter}'
        report = cs.run_job(cpath, out, **kwargs)
        return report,out

    def rejected(self, cfg, text=None, **kwargs):
        self.counter += 1
        cpath = self.base/f'config_{self.counter}.json'
        cpath.write_text(json.dumps(cfg))
        out=self.base/f'run_{self.counter}'
        with self.assertRaises(cs.ProcessingError) as ctx:
            cs.run_job(cpath,out,**kwargs)
        if text:self.assertIn(text,str(ctx.exception))
        self.assertEqual({p.name for p in out.iterdir()}
                         - {'debug_overlay.png', 'diagnostics.json', 'metrics.json', 'containers'},
                         {'report.json'})
        r=json.loads((out/'report.json').read_text())
        self.assertEqual(r['status'],'rejected')
        self.assertFalse(r['result_created'])
        self.assertFalse(r['fallback_to_edge'])
        return r

    def overlap(self, seed=5):
        q=[[0,0],[449,0],[449,219],[0,219]]
        return {'schema_version':1,'mode':'single','height':220,'gap_px':12,
                'sources':{name:{'path':str(self.fixtures/f'{name}_{seed}.png'),
                                 'expected_size_wh':[450,220]} for name in ('left','right')},
                'containers':[{'key':'box_a','container_id':'TEST-A', 'method':'overlap',
                    'same_surface_confirmed':True,
                    'matching':{'min_inliers':20,'feather_px':24},
                    'regions':[{'source':n,'quad':q} for n in ('left','right')]}]}

    def test_01_single_matches_previous_output_pixels(self):
        report,out=self.process(self.recipe())
        expected=json.loads((ROOT/'tests'/'regression_reference.json').read_text())['single_grey']
