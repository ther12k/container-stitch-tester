"""Regression, grouping, conservative overlap, CLI and rejection tests.

No test establishes automatic classification, arbitrary-camera robustness, metric
calibration or physical correctness of an edge join. Synthetic scenes and crops
provide controlled correspondence only; the three user examples use fixed corners.
"""
